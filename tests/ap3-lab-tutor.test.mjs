import test from 'node:test';
import assert from 'node:assert/strict';
import { chapterLabs } from '../src/ap3-labs.js';
import { springLabTutorContext } from '../src/ap3-labs-tutor.js';
import { buildTutorMessages, retrieveSources } from '../src/tutor-context.js';

test('a guided route sends only the learner’s current stop and previously confirmed steps', () => {
  const activity = chapterLabs[21][0];
  const route = activity.routes[1];
  const state = { activityIndex:0, route:1, step:0, routeChoice:null, routeCorrect:false };
  const snapshot = () => springLabTutorContext(21,activity,state);
  let context = snapshot();
  assert.equal(context.reference,'21.1');
  assert.equal(context.diagram.state.route,'Left foot');
  assert.equal(context.diagram.answer,'');
  const prompt = buildTutorMessages('What comes next?',[],context).messages[0].content;
  assert.match(prompt,/Interstitial space in the left foot/);
  assert.ok(!prompt.includes(route.steps[0][3]));
  assert.ok(!prompt.includes('left venous angle'));
  assert.match(prompt,/Keep the pending answer and future stops hidden/);
  state.routeChoice=2;
  context=snapshot();
  assert.equal(context.diagram.prediction,route.steps[0][2]);
  assert.equal(context.diagram.answer,'');
  assert.ok(!retrieveSources('Explain',context)[0].text.includes(route.steps[0][3]));
  state.routeChoice=0; state.routeCorrect=true;
  context=snapshot();
  assert.equal(context.diagram.answer,route.steps[0][3]);
  assert.ok(!retrieveSources('Explain',context)[0].text.includes(route.steps[1][3]));
  state.step=1;state.routeCorrect=false;state.routeChoice=null;
  assert.equal(snapshot().diagram.state.location,route.steps[0][0]);
  state.step=route.steps.length;
  assert.equal(snapshot().diagram.state.status,'Complete');
});

test('active experiment context follows settings, submitted prediction, and only the selected frame', () => {
  const activity=chapterLabs[26][0];
  const state={activityIndex:0,values:{initialVol:1,outside:350},choice:null,frame:0};
  const snapshot=()=>springLabTutorContext(26,activity,state);
  const data=activity.run(state.values);
  const pending=snapshot(), visible=retrieveSources('Explain the final result',pending);
  assert.equal(pending.diagram.state['Effective solute concentration in bath'],'350 mOsm/L');
  assert.match(pending.text,/300\.0 mOsm\/L/);
  assert.equal(pending.diagram.prediction,'');
  assert.ok(!JSON.stringify(pending).includes(data.frames.at(-1)[1]));
  assert.ok(!visible[0].text.includes(data.choices[0]));
  assert.deepEqual(retrieveSources('Hint',{...pending,assessmentMode:'exam'}),[]);
  state.choice=1;
  const checked=snapshot();
  assert.equal(checked.diagram.prediction,data.choices[1]);
  assert.ok(checked.diagram.answer.includes(data.choices[0]));
  assert.equal(checked.diagram.state['Selected result frame'],data.frames[0][0]);
  assert.ok(!checked.text.includes(data.frames.at(-1)[1]));
  state.frame=data.frames.length-1;
  assert.ok(snapshot().text.includes(data.frames.at(-1)[1]));
  state.values.outside=200;state.choice=null;state.frame=0;
  assert.equal(snapshot().diagram.answer,'');
  assert.ok(!snapshot().text.includes(data.frames.at(-1)[1]));
});
